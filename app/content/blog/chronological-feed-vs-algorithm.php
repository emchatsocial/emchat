<h2>Two ways to build a feed</h2>
<p>A <strong>chronological feed</strong> is the simplest possible design. It shows posts from the accounts you follow, newest first. When you reach posts you've already seen, you're caught up.</p>
<p>A <strong>ranked</strong> or <strong>algorithmic feed</strong> collects a much larger pool of possible posts, including from accounts you don't follow, and scores each one on how likely you are to react to it: to like, comment, share, watch to the end or simply keep scrolling. The highest-scoring posts go to the top. Most of the big social apps use some version of this, and many say so openly in their help pages.</p>

<h2>Why ranked feeds hide posts from your friends</h2>
<p>A ranked feed isn't trying to show you everything your friends post. It's trying to show you whatever is most likely to keep you engaged. A quiet update from a friend with few likes can easily lose to a viral clip from someone you've never heard of. The result:</p>
<ul>
  <li><strong>You miss posts</strong> from people you deliberately chose to follow.</li>
  <li><strong>Your friends miss yours</strong>, so posting starts to feel like shouting into a void.</li>
  <li><strong>There's no "end"</strong>. A ranked feed can always find one more thing to show you, which makes it hard to stop.</li>
  <li><strong>It's hard to know why</strong> you're seeing something, or how to see less of it.</li>
</ul>

<h2>What ranked feeds do well</h2>
<p>To be fair, ranking does solve real problems. If you follow thousands of accounts, a pure timeline can be overwhelming, and ranking can surface a post you'd genuinely hate to miss. It also helps new people find an audience. The trade-off is control: the app, not you, decides what matters.</p>

<h2>What a chronological feed feels like</h2>
<p>Switching to a chronological feed changes the experience more than you'd expect:</p>
