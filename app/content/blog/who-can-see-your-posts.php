<p class="prose__lede">EMChat Media gives you two layers of control: who can see each individual post, and how open your account is as a whole. This guide explains what each setting does and how they combine.</p>

<h2>Choosing who sees each post</h2>
<p>Every time you write a post, you pick its audience from the menu next to the Post button. You can change it later by editing the post.</p>
<ul>
  <li><strong>Public</strong>: anyone can see it on your profile or through a direct link, even people who don't follow you and people who aren't signed in. It isn't pushed into strangers' feeds or onto Explore.</li>
  <li><strong>Followers only</strong>: only people you've accepted as followers can see it. It shows up in their home feed and on your profile when they visit.</li>
  <li><strong>Only me</strong>: nobody else can see it. Use it for drafts, notes or posts you want to keep but no longer share.</li>
</ul>

<h2>Private account</h2>
<p>Turning on <strong>Private account</strong> (Settings &rarr; Privacy &amp; safety) changes who can follow you and see your account:</p>
<ul>
  <li>New followers have to <strong>request</strong> to follow you, and you approve or decline each one.</li>
  <li>Your <strong>followers and following lists</strong> are only visible to your approved followers.</li>
  <li>Your <strong>Followers only</strong> posts are only visible to approved followers.</li>
  <li>Posts you mark <strong>Public</strong> stay visible to everyone, so you can keep your account private and still share the occasional post openly.</li>
</ul>
<p>If you want nothing visible to people outside your followers, keep your account private and choose <strong>Followers only</strong> for your posts.</p>

<h2>Discoverable</h2>
<p><strong>Discoverable</strong> controls whether people can find you in EMChat Media's search. If your account is also public, it lets search engines like Google index your profile and your Public posts. Nothing from a private account is indexed, and Followers only and Only me posts never are.</p>
<p>Turn Discoverable off if you only want to be found by people who already know your username.</p>

<h2>Quick reference</h2>
<ul>
  <li><strong>Public post, public account</strong>: visible to everyone. Can appear in Google if Discoverable is on.</li>
