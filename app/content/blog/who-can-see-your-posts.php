  <li><strong>Followers only post</strong>: visible to your accepted followers only.</li>
  <li><strong>Only me post</strong>: visible to you only.</li>
</ul>

<h2>Blocking and muting</h2>
<ul>
  <li><strong>Mute</strong> someone to stop seeing their posts in your feed. They aren't told.</li>
  <li><strong>Block</strong> someone to cut contact completely. Follows are removed in both directions, they can't see your profile or posts, they can't message you (including in an existing chat), and they can't trigger notifications for you. You can see and undo blocks in Settings &rarr; Privacy &amp; safety.</li>
</ul>

<h2>Messages</h2>
<p>If someone you don't follow messages you, it arrives as a <strong>message request</strong> rather than landing in your inbox. You can accept it to reply, or delete it, and they aren't told either way.</p>

<h2>Your data</h2>
<p>From Settings you can <strong>export</strong> everything you've shared, or <strong>delete your account</strong>, at any time. Photos you upload are stripped of location and other metadata before they're stored.</p>
