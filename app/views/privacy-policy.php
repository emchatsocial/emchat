  <h1>Privacy Policy</h1>
  <p class="muted">Last updated November 15, 2026</p>

  <p>This Privacy Policy describes how EMChat Media collects, uses and protects personal information when you use emchat.social and its related services. It also explains the choices available to you.</p>

  <h2>1. Information we collect</h2>
  <p><strong>Account information.</strong> An email address is the only information required to create an account. We use it to send sign-in links and essential notices about your account.</p>
  <p><strong>Profile information.</strong> The username, display name, biography and profile photo you choose to add.</p>
  <p><strong>Content you create.</strong> Posts, replies, photos, messages and attachments, together with interactions such as likes, follows, blocks and mutes. Direct messages are end-to-end encrypted, as described in section 2, so we store them only in a form we cannot read.</p>
  <p><strong>Encryption keys.</strong> Your browser creates an encryption key for your messages. We store its public part, which others use to send you encrypted messages. If you set a backup PIN, we also store a copy of your private keys that is encrypted with that PIN in your browser. We never receive your PIN or your private keys in readable form.</p>
  <p><strong>Usage information.</strong> We record when you were last active so that the service functions correctly. We also use Google Analytics to understand overall traffic, such as visitor numbers, popular pages and approximate regions. Google processes technical data, including IP addresses, on our behalf for this purpose.</p>
  <p><strong>Messages sent through our contact form.</strong> Your email address and message are forwarded to our team so that we can respond.</p>

  <h2>2. End-to-end encryption</h2>
  <p>Direct messages, including group chats and the photos, videos and files sent in them, are encrypted on your device before they are sent. Only the people in the conversation hold the keys to read them. EMChat Media stores the encrypted messages and attachments but cannot read them.</p>
  <ul>
    <li>Encryption is on by default. A conversation is end-to-end encrypted once everyone in it has opened EMChat Media since encryption was introduced on November 15, 2026. Until then, the conversation shows that it is not yet encrypted.</li>
    <li>Messages and attachments sent before that date are not end-to-end encrypted.</li>
    <li>If you clear your browser data or use a new browser, you need your backup PIN to read earlier encrypted messages. We cannot recover messages or PINs for you.</li>
  </ul>

  <h2>3. How we use information</h2>
  <ul>
    <li>To provide, operate and secure the service.</li>
    <li>To deliver your content to the audience you select.</li>
    <li>To send sign-in links and essential account communications.</li>
    <li>To prevent spam and abuse, and to review content that has been reported.</li>
    <li>To understand aggregate usage so that we can improve the service.</li>
  </ul>

  <h2>4. What we do not do</h2>
  <ul>
    <li>We do not use advertising trackers, advertising SDKs or social media tracking pixels.</li>
    <li>We do not sell, rent or share personal information with advertisers or data brokers.</li>
    <li>We do not carry out behavioural profiling or targeted advertising.</li>
    <li>We do not scan your messages. Our staff do not browse posts or messages, and encrypted messages cannot be read by us.</li>
  </ul>

  <h2>5. Reports</h2>
  <p>Content is reviewed only when another user reports it, and the review is limited to what was reported. When you report an end-to-end encrypted message, your browser shares the text of that message with us so that we can review it. You are told this before you submit the report.</p>

  <h2>6. Photo metadata</h2>
  <p>Photos are re-encoded before they are stored, which removes embedded metadata such as camera details and GPS location. Photos in posts are re-encoded on our servers. Photos in encrypted messages are re-encoded in your browser before they are encrypted. Videos and other files are stored as they were sent.</p>

  <h2>7. Cookies</h2>
  <p>We use one strictly necessary cookie to keep you signed in. Google Analytics sets additional cookies to distinguish visits; these are not used for advertising. Your browser also stores your encryption keys locally so that you can read your messages; they are not sent to us.</p>

  <h2>8. Service providers</h2>
  <p>We rely on a limited number of providers to operate the service: web hosting, a content delivery and security network, an email delivery service and Google Analytics. These providers process data only as needed to perform their services for us. They receive end-to-end encrypted messages only in encrypted form.</p>

  <h2>9. Your choices and rights</h2>
  <ul>
    <li><strong>Visibility.</strong> You can make your account private and set each post to Public, Followers only or Only me.</li>
    <li><strong>Search engines.</strong> You can turn off Discoverable to keep your profile and posts out of search results.</li>
    <li><strong>Encryption.</strong> In Settings &rarr; Encryption you can set, change or remove your backup PIN, create a new encryption key, or remove your key from a shared browser.</li>
    <li><strong>Access and portability.</strong> You can download a copy of your data in JSON format from Settings &rarr; Account. End-to-end encrypted messages are included in their encrypted form.</li>
    <li><strong>Deletion.</strong> You can permanently delete your account at any time from Settings &rarr; Account. This removes your profile, posts, the messages you sent, uploaded photos and files, and your encryption keys and backups.</li>
  </ul>
  <p>For any other request concerning your personal information, please contact us using the details below.</p>

  <h2>10. Data retention</h2>
  <p>Content is retained until you delete it or close your account. Sign-in links expire after 15 minutes. Records used for rate limiting are removed automatically within one hour.</p>

  <h2>11. Changes to this policy</h2>
  <p>We may update this policy from time to time. The date at the top of this page shows when it was last revised, and significant changes will be announced on the service.</p>

  <h2>12. Contact</h2>
  <p>For questions about this policy or your personal information, please contact <a href="mailto:egzon@emchat.social">egzon@emchat.social</a>.</p>
